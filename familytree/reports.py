"""Text outputs: Mermaid diagrams, the gap report and the list of ancestors."""

from __future__ import annotations

from pathlib import Path

from .dates import TODAY
from .i18n import tr
from .model import Hint, Tree
from .schema import LIFE_EVENTS

MERMAID_CLASSES = """\
  classDef male fill:#dce8fa,stroke:#3d6fb6,color:#111
  classDef female fill:#fbe1eb,stroke:#b6416f,color:#111
  classDef unk fill:#ececec,stroke:#888,color:#111
  classDef maleH fill:#dce8fa,stroke:#3d6fb6,color:#111,stroke-dasharray:5 4
  classDef femaleH fill:#fbe1eb,stroke:#b6416f,color:#111,stroke-dasharray:5 4
  classDef unkH fill:#ececec,stroke:#888,color:#111,stroke-dasharray:5 4
  classDef fam fill:#fff6dd,stroke:#b8962e,color:#111"""

LEVEL_ICON = {1: "🔴", 2: "🟠", 3: "⚪"}


def _mm(text: str) -> str:
    return str(text).replace('"', "#quot;").replace("<", "#60;").replace(">", "#62;")


def mermaid(tree: Tree, pids: list[str], fids: list[str], public: bool) -> str:
    if not pids:
        return ""
    out = ["flowchart TB", "  %% " + tr("Generated by scripts/build.py — do not edit by hand."), MERMAID_CLASSES]
    groups: dict[str, list[str]] = {}
    for pid in pids:
        p = tree.persons[pid]
        if public and tree.living(pid):
            lines = [tr("Living person")]
        else:
            nums = tree.kekule.get(pid)
            lines = [(f"[{', '.join(map(str, nums))}] " if nums else "") + tree.name(pid)] + tree.life_lines(p)
        out.append(f'  {pid}["{"<br/>".join(_mm(x) for x in lines)}"]')
        cls = {"M": "male", "F": "female"}.get(p.get("sex"), "unk") + ("H" if p.get("confidence") == "hypothesis" else "")
        groups.setdefault(cls, []).append(pid)
    shown = set(pids)
    for fid in fids:
        f = tree.families[fid]
        md = tree.date(f, "marriage")
        hidden = public and any(tree.living(x) for x in (f.get("husband"), f.get("wife")) if x)
        out.append(f'  {fid}(["{_mm("⚭ " + md.text() if md and not hidden else "⚭")}"])')
        groups.setdefault("fam", []).append(fid)
        for role in ("husband", "wife"):
            if f.get(role) in shown:
                out.append(f"  {f[role]} --- {fid}")
        for c in f.get("children") or []:
            if c in shown:
                out.append(f"  {fid} --> {c}")
    out += [f"  class {','.join(ids)} {cls}" for cls, ids in groups.items()]
    return "\n".join(out) + "\n"


def mermaid_views(tree: Tree, public: bool) -> tuple[str, str]:
    full = mermaid(tree, list(tree.persons), list(tree.families), public)
    anc = sorted(tree.kekule, key=lambda pid: min(tree.kekule[pid]))
    return full, mermaid(tree, anc, tree.ancestral_families(), public)


def md_hints(hints: list[Hint]) -> list[str]:
    out = []
    for h in hints:
        out.append(f"- {LEVEL_ICON[h.level]} {h.text}")
        out += [f"  - {d}" for d in h.details]
        out += [f"  - [{label}]({url})" for label, url in h.links]
    return out


def generation_name(g: int) -> str:
    """Name of generation g in Kekule terms (2 = parents, 3 = grandparents …)."""
    names = {2: tr("parents"), 3: tr("grandparents"), 4: tr("great-grandparents"), 5: tr("great-great-grandparents")}
    return names[g] if g in names else tr("{n} generations back", n=g - 1)


def completeness(tree: Tree) -> list[str]:
    numbers = {n for ns in tree.kekule.values() for n in ns}
    if not numbers:
        return []
    top = max(n.bit_length() for n in numbers)
    out = []
    for g in range(2, top + 2):
        have = sum(1 for n in numbers if n.bit_length() == g)
        out.append(tr("- generation {n} ({name}): {have}/{total}", n=g, name=generation_name(g), have=have, total=2 ** (g - 1)))
    return out


def write_gaps(tree: Tree, path: Path) -> None:
    anc = sorted(tree.kekule, key=lambda pid: min(tree.kekule[pid]))
    ends = [pid for pid in anc if len(tree.parents(pid)) < 2]
    L = [tr("# Gaps in the data and research suggestions"), "",
         tr("_Generated {date} by `scripts/build.py` — do not edit by hand._", date=TODAY.isoformat()), "",
         tr("🔴 priority · 🟠 important · ⚪ supplementary. Geneteka links are ready-made queries; always confirm "
            "an index hit on the scan of the record."), "", tr("## Summary"), "",
         tr("- persons: {persons}, families: {families}, places: {places}, sources: {sources}", persons=len(tree.persons),
            families=len(tree.families), places=len(tree.places), sources=len(tree.sources)),
         tr("- ancestors of the proband in the data: {n}", n=len(anc))]
    L += completeness(tree)
    if ends:
        L += ["", tr("**Ends of lines** (ancestors missing one or both parents):"), ""]
        for pid in ends:
            life = "; ".join(tree.life_lines(tree.persons[pid]))
            L.append(f"- {', '.join(map(str, tree.kekule[pid]))} · {tree.name(pid)}" + (f" ({life})" if life else "") + f" — `{pid}`")
    L += ["", tr("## 1. Ancestors of the proband"), ""]
    if not tree.project.get("proband"):
        L.append(tr("_Set `proband` in data/project.yaml to determine the line of ancestors._"))
    for pid in anc:
        if hints := tree.person_hints(pid):
            life = "; ".join(tree.life_lines(tree.persons[pid]))
            L += [f"### {', '.join(map(str, tree.kekule[pid]))} · {tree.name(pid)}" + (f" · {life}" if life else "") + f" · `{pid}`", ""]
            L += md_hints(hints) + [""]
    L += [tr("## 2. Marriages of the ancestors"), ""]
    anc_fams = tree.ancestral_families()
    for fid in anc_fams:
        if hints := tree.family_hints(fid):
            f = tree.families[fid]
            L += [f"### {tree.name(f.get('husband'))} ⚭ {tree.name(f.get('wife'))} · `{fid}`", ""] + md_hints(hints) + [""]
    L += [tr("## 3. Other persons and families (collateral relatives)"), "",
          tr("_Siblings of ancestors are often the key to a brick wall: their records name the same parents and witnesses._"), ""]
    for pid in tree.persons:
        if pid not in tree.kekule and (hints := [h for h in tree.person_hints(pid) if h.level < 3]):
            L += [f"### {tree.name(pid)} · `{pid}`", ""] + md_hints(hints) + [""]
    for fid in tree.families:
        if fid not in anc_fams and (hints := tree.family_hints(fid)):
            f = tree.families[fid]
            L += [f"### {tree.name(f.get('husband'))} ⚭ {tree.name(f.get('wife'))} · `{fid}`", ""] + md_hints(hints) + [""]
    L += [tr("## 4. Places to complete"), ""]
    L += [tr("- `{id}` {name}: missing {fields}", id=plid, name=tree.places[plid]["name"], fields=", ".join(m))
          for plid, m in tree.place_gaps()] or [tr("_None._")]
    L += ["", tr("## 5. Validation warnings"), ""]
    L += [f"- {w}" for w in tree.warnings] or [tr("_None._")]
    L += ["", tr("## 6. Geography"), ""] + tree.geo(living=True).gap_lines()
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def write_ancestors(tree: Tree, path: Path) -> None:
    by_num = {n: pid for pid, ns in tree.kekule.items() for n in ns}
    L = [tr("# List of ancestors (Kekule numbering)"), "",
         tr("_Generated {date} by `scripts/build.py`. Proband = 1; father of person n = 2n, mother = 2n+1._", date=TODAY.isoformat()), ""]
    L += completeness(tree)
    L += ["", tr("| No. | Gen. | Person | Birth | Marriage (of the parents of no. n/2) | Death | Sources | ID |"), "|---|---|---|---|---|---|---|---|"]
    rows = []
    for n, pid in by_num.items():
        p = tree.persons[pid]
        birth = tree.event_text(tree.ev(p, "birth")) or (tr("bapt. {event}", event=tree.event_text(tree.ev(p, "baptism"))) if tree.ev(p, "baptism") else "")
        death = tree.event_text(tree.ev(p, "death")) or (tr("bur. {event}", event=tree.event_text(tree.ev(p, "burial"))) if tree.ev(p, "burial") else "")
        marriage = ""
        if n > 1 and (f := tree.parents_family(by_num[n // 2])):
            marriage = tree.event_text(tree.ev(f, "marriage"))
        srcs = {s for k in LIFE_EVENTS for s in tree.ev(p, k).get("sources") or []}
        srcs |= {s for e in p.get("events") or [] if isinstance(e, dict) for s in e.get("sources") or []}
        srcs |= {s for fid in tree.spouse_in.get(pid, []) for s in tree.ev(tree.families[fid], "marriage").get("sources") or []}
        rows.append((n, f"| {n} | {n.bit_length()} | {tree.name(pid)} | {birth} | {marriage} | {death} | {len(srcs)} | `{pid}` |"))
        for k, missing in ((2 * n, tr("_? (father of no. {n})_", n=n)), (2 * n + 1, tr("_? (mother of no. {n})_", n=n))):
            if k not in by_num:
                rows.append((k, f"| {k} | {k.bit_length()} | {missing} |  |  |  |  |  |"))
    L += [r for _, r in sorted(rows)]
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
