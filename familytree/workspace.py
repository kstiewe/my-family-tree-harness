"""The private workspace: where the family data lives, outside this repository.

A workspace is any directory with `data/project.yaml`. Layout:

    <workspace>/
      INSTRUCTIONS.md   private instructions for the agent (artifact URLs, research regions, open leads)
      privacy.yaml      extra terms for the privacy guard and allowed phrases
      data/             project.yaml, persons.yaml, families.yaml, places.yaml, sources.yaml
      research/         log.md (search log) and private research notes
      output/           generated by build.py

The workspace is found in this order:
  1. --workspace PATH
  2. the FAMILYTREE_WORKSPACE environment variable
  3. the current directory or one of its parents
  4. the `.workspace` file in the application root (one line: a path), written by `workspace.py link`
  5. ~/.config/familytree/workspace (same format)
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

APP_ROOT = Path(__file__).resolve().parent.parent
ENV_VAR = "FAMILYTREE_WORKSPACE"
POINTER = APP_ROOT / ".workspace"
SKELETON = Path(__file__).parent / "skeleton"


def user_config() -> Path:
    return Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "familytree" / "workspace"


def is_workspace(path: Path) -> bool:
    return (path / "data" / "project.yaml").is_file()


@dataclass
class Workspace:
    root: Path
    found_via: str

    @property
    def data(self) -> Path:
        return self.root / "data"

    @property
    def output(self) -> Path:
        return self.root / "output"

    @property
    def research(self) -> Path:
        return self.root / "research"

    @property
    def instructions(self) -> Path:
        return self.root / "INSTRUCTIONS.md"

    @property
    def privacy(self) -> Path:
        return self.root / "privacy.yaml"

    def project(self) -> dict:
        import yaml
        try:
            return yaml.safe_load((self.data / "project.yaml").read_text(encoding="utf-8")) or {}
        except (OSError, yaml.YAMLError):
            return {}


def _read_pointer(path: Path) -> Path | None:
    try:
        line = path.read_text(encoding="utf-8").strip().splitlines()[0].strip()
    except (OSError, IndexError):
        return None
    p = Path(line).expanduser()
    return p if p.is_absolute() else (path.parent / p).resolve()


def find_workspace(explicit: str | Path | None = None, cwd: Path | None = None) -> Workspace | None:
    if explicit:
        p = Path(explicit).expanduser().resolve()
        return Workspace(p, "--workspace") if is_workspace(p) else None
    if os.environ.get(ENV_VAR):
        p = Path(os.environ[ENV_VAR]).expanduser().resolve()
        return Workspace(p, ENV_VAR) if is_workspace(p) else None
    here = (cwd or Path.cwd()).resolve()
    for d in (here, *here.parents):
        if is_workspace(d):
            return Workspace(d, "current directory")
    for pointer, label in ((POINTER, f"{POINTER.name} file in the application root"), (user_config(), str(user_config()))):
        p = _read_pointer(pointer)
        if p and is_workspace(p):
            return Workspace(p, label)
    return None


NOT_FOUND = ("No workspace found. Create one with `python3 scripts/workspace.py init PATH`, or connect an existing one "
             "with `python3 scripts/workspace.py link PATH` (or set FAMILYTREE_WORKSPACE). A workspace is a directory "
             "with data/project.yaml.")


# ------------------------------------------------------------------ commands

def cmd_where(ws: Workspace | None, as_json: bool) -> int:
    if as_json:
        print(json.dumps({"workspace": str(ws.root) if ws else None, "found_via": ws.found_via if ws else None}))
    else:
        print(f"{ws.root}  (found via {ws.found_via})" if ws else NOT_FOUND)
    return 0 if ws else 1


def cmd_link(path: str, user: bool) -> int:
    p = Path(path).expanduser().resolve()
    if not is_workspace(p):
        print(f"{p} is not a workspace (no data/project.yaml).", file=sys.stderr)
        return 1
    target = user_config() if user else POINTER
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(f"{p}\n", encoding="utf-8")
    print(f"Linked {p} via {target}")
    return 0


def cmd_init(path: str, name: str, lang: str, git: bool) -> int:
    root = Path(path).expanduser().resolve()
    if is_workspace(root):
        print(f"{root} already is a workspace; nothing changed.", file=sys.stderr)
        return 1
    if root.resolve() == APP_ROOT or APP_ROOT in root.parents:
        print("Refusing to create a workspace inside the application repository: family data must live outside it.",
              file=sys.stderr)
        return 1
    for src in SKELETON.rglob("*"):
        if src.is_file():
            dest = root / src.relative_to(SKELETON)
            dest.parent.mkdir(parents=True, exist_ok=True)
            if not dest.exists():
                text = src.read_text(encoding="utf-8").replace("__NAME__", name).replace("__LANG__", lang)
                dest.write_text(text, encoding="utf-8")
    (root / "output").mkdir(exist_ok=True)
    if git and not (root / ".git").exists() and shutil.which("git"):
        subprocess.run(["git", "init", "-q", str(root)], check=False)
    print(f"Workspace created: {root}\nConnect it: python3 scripts/workspace.py link {root}")
    return 0


def context_text(ws: Workspace | None) -> str:
    """What an agent needs at the start of a session (printed by the SessionStart hook)."""
    if not ws:
        return "# Family-tree workspace\n\n" + NOT_FOUND + "\n"
    from . import i18n
    from .model import Tree
    project = ws.project()
    lines = ["# Family-tree workspace (private — never copy its contents into the application repository)", "",
             f"- workspace: {ws.root} (found via {ws.found_via})",
             f"- data: {ws.data}", f"- outputs: {ws.output}", f"- research notes and search log: {ws.research}",
             f"- language for reports and for talking to the user: {i18n.resolve(None, project)}"]
    try:
        tree = Tree(ws.data)
        ids = tree.next_ids()
        lines += [f"- records: {len(tree.persons)} persons, {len(tree.families)} families, {len(tree.places)} places, "
                  f"{len(tree.sources)} sources; {len(tree.errors)} errors, {len(tree.warnings)} warnings",
                  f"- next free IDs: {ids['person']} {ids['family']} {ids['place']} {ids['source']}"]
    except Exception as e:  # never break session start
        lines.append(f"- could not load the data: {e}")
    if ws.instructions.is_file():
        lines += ["", f"## Private instructions ({ws.instructions})", "", ws.instructions.read_text(encoding="utf-8").strip()]
    else:
        lines += ["", f"(No private instructions: {ws.instructions} does not exist.)"]
    return "\n".join(lines) + "\n"


def cmd_serve(ws: Workspace | None, port: int) -> int:
    if not ws:
        print(NOT_FOUND, file=sys.stderr)
        return 1
    import functools
    import http.server
    ws.output.mkdir(exist_ok=True)
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(ws.output))
    with http.server.ThreadingHTTPServer(("127.0.0.1", port), handler) as httpd:
        print(f"Serving {ws.output} on http://127.0.0.1:{port}/", flush=True)
        httpd.serve_forever()
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Find, create and connect the private data workspace.",
                                 formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    ap.add_argument("--workspace", help="workspace directory (overrides the search order)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("where", help="print the active workspace")
    w.add_argument("--json", action="store_true")
    ln = sub.add_parser("link", help="remember a workspace in .workspace (or in the user config with --user)")
    ln.add_argument("path")
    ln.add_argument("--user", action="store_true", help=f"write {user_config()} instead")
    it = sub.add_parser("init", help="create a new, empty workspace")
    it.add_argument("path")
    it.add_argument("--name", default="Family tree")
    it.add_argument("--lang", default="en", help="language of reports (en, pl …)")
    it.add_argument("--git", action="store_true", help="also run git init (a private repository, never public)")
    cx = sub.add_parser("context", help="print the workspace summary and private instructions for an agent")
    cx.add_argument("--hook", action="store_true", help="never fail (for the SessionStart hook)")
    sv = sub.add_parser("serve", help="serve output/ on localhost for previewing the tree")
    sv.add_argument("--port", type=int, default=8765)
    a = ap.parse_args(argv)

    if a.cmd == "link":
        return cmd_link(a.path, a.user)
    if a.cmd == "init":
        return cmd_init(a.path, a.name, a.lang, a.git)
    ws = find_workspace(a.workspace)
    if a.cmd == "where":
        return cmd_where(ws, a.json)
    if a.cmd == "context":
        try:
            print(context_text(ws), end="")
        except Exception as e:
            print(f"# Family-tree workspace\n\nCould not read the workspace: {e}")
            return 0
        return 0 if (ws or a.hook) else 1
    if a.cmd == "serve":
        return cmd_serve(ws, a.port)
    return 2


if __name__ == "__main__":
    sys.exit(main())
